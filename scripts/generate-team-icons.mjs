#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TAG_RULES, tagsFor } from "./team-icon-tags.mjs";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

export function kebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

/**
 * The only markup a team icon may be made of. Everything the emitted bodies
 * reach is `dangerouslySetInnerHTML`, so a `<script>`, a `<foreignObject>` or
 * an `on*` handler slipped into a future source file would run in the app.
 * Anything outside these two lists stops the build instead.
 */
const ALLOWED_ELEMENTS = new Set(
  "path circle ellipse rect line polyline polygon g".split(" "),
);
const ALLOWED_ATTRIBUTES = new Set(
  "d cx cy r rx ry x y x1 y1 x2 y2 width height points fill-rule clip-rule transform opacity fill-opacity".split(
    " ",
  ),
);

/**
 * Both name patterns admit `:` so a NAMESPACED name is captured whole and put
 * to the allowlist as it is written. Stopping at the colon would read
 * `xlink:href` as `href` and `<svg:script>` as `svg`, judging a name the
 * document never used: `xlink:href` is a live script vector in an SVG that
 * ships through `dangerouslySetInnerHTML`. Nothing on either allowlist has a
 * colon, so every namespaced name is rejected, which is the fail-closed answer.
 */
function assertDrawingOnly(id, body) {
  for (const [, element] of body.matchAll(/<\/?([a-zA-Z][\w:-]*)/g)) {
    if (!ALLOWED_ELEMENTS.has(element)) {
      throw new Error(`Symbol "${id}": <${element}> is not a drawing element`);
    }
  }
  for (const [, attribute] of body.matchAll(/\s([a-zA-Z][\w:-]*)\s*=/g)) {
    if (!ALLOWED_ATTRIBUTES.has(attribute)) {
      throw new Error(
        `Symbol "${id}": attribute "${attribute}" is not allowed`,
      );
    }
  }
}

export function parseSymbols(source) {
  return [
    ...source.matchAll(
      /<symbol\s+id="([^"]+)"\s+viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g,
    ),
  ].map(([, id, viewBox, rawBody]) => {
    const body = rawBody
      .replace(/\sfill=("[^"]*"|'[^']*')/g, "")
      .replace(/></g, ">\n<")
      .trim();
    // Checked on what actually SHIPS, after the fill strip, so the allowlist
    // judges the exact markup the app will render.
    assertDrawingOnly(id, body);
    return { key: kebabCase(id), viewBox, body };
  });
}

function dataModule(entries, index) {
  const rows = entries.map(
    ({ key, viewBox, body }) =>
      `  ${JSON.stringify(key)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`,
  );
  return `/** Generated by scripts/generate-team-icons.mjs. Do not edit. */\nexport const SIDEBAR_GROUP_GLYPHS_${index} = {\n${rows.join("\n")}\n} as const;\n`;
}

export async function generate(sourcePath) {
  const icons = parseSymbols(await readFile(sourcePath, "utf8")).sort(
    (left, right) => {
      const category = (key) =>
        TAG_RULES.findIndex(([, pattern]) => pattern.test(key));
      return category(left.key) - category(right.key);
    },
  );
  if (icons.length === 0)
    throw new Error(`No SVG symbols found in ${sourcePath}`);
  if (new Set(icons.map(({ key }) => key)).size !== icons.length) {
    throw new Error("Kebab-case icon keys are not unique");
  }
  const chunks = Array.from({ length: 5 }, (_, index) =>
    icons.slice(
      index * Math.ceil(icons.length / 5),
      (index + 1) * Math.ceil(icons.length / 5),
    ),
  );
  await Promise.all(
    chunks.map((chunk, index) =>
      writeFile(
        path.join(
          repoRoot,
          `ui/layout/src/sidebar-group-glyph-data-${index + 1}.ts`,
        ),
        dataModule(chunk, index + 1),
      ),
    ),
  );
  const tags = icons
    .map(
      ({ key }) => `  ${JSON.stringify(key)}: ${JSON.stringify(tagsFor(key))},`,
    )
    .join("\n");
  await writeFile(
    path.join(repoRoot, "ui/layout/src/sidebar-group-glyph-tags.ts"),
    `/** Generated curated concept tags. Name words are added by the matcher. */\nimport type { SidebarGroupGlyphName } from "./sidebar-group-glyphs";\n\nexport const SIDEBAR_GROUP_GLYPH_TAGS = {\n${tags}\n} satisfies Record<SidebarGroupGlyphName, readonly string[]>;\n`,
  );
  return icons;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  // The committed asset by default, so `pnpm generate:team-icons` regenerates
  // exactly what is in the tree; an argument overrides it with a new source.
  const sourcePath =
    process.argv[2] ?? path.join(repoRoot, "ui/layout/icons/team-icons.svg");
  try {
    const icons = await generate(sourcePath);
    process.stdout.write(`Generated ${icons.length} team icons.\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exit(1);
  }
}
