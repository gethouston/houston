export function kebabCase(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

export function parseSymbols(source) {
  return [
    ...source.matchAll(
      /<symbol\s+id="([^"]+)"\s+viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g,
    ),
  ].map(([, id, viewBox, rawBody]) => ({
    key: kebabCase(id),
    viewBox,
    body: rawBody
      .replace(/\sfill=("[^"]*"|'[^']*')/g, "")
      .replace(/></g, ">\n<")
      .trim(),
  }));
}

