export function tagsFor(key) {
  const tags = [];
  for (const [words, pattern] of TAG_RULES) {
    if (pattern.test(key)) tags.push(...words.split(" "));
  }
  if (tags.length < 2) tags.push("general", "symbol");
  return [...new Set(tags)].filter((tag) => !key.split("-").includes(tag));
}

function dataModule(entries, index) {
  const rows = entries.map(
    ({ key, viewBox, body }) =>
      `  ${JSON.stringify(key)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`,
  );
  return `/** Generated by scripts/generate-team-icons.mjs. Do not edit. */\nexport const SIDEBAR_GROUP_GLYPHS_${index} = {\n${rows.join("\n")}\n} as const;\n`;
}

export async function generate(sourcePath) {
  const icons = parseSymbols(await readFile(sourcePath, "utf8")).sort(
    (left, right) => {
      const category = (key) =>
        TAG_RULES.findIndex(([, pattern]) => pattern.test(key));
      return category(left.key) - category(right.key);
    },
  );
  if (icons.length === 0)
    throw new Error(`No SVG symbols found in ${sourcePath}`);
  if (new Set(icons.map(({ key }) => key)).size !== icons.length) {
    throw new Error("Kebab-case icon keys are not unique");
  }
  const chunks = Array.from({ length: 5 }, (_, index) =>
    icons.slice(
      index * Math.ceil(icons.length / 5),
      (index + 1) * Math.ceil(icons.length / 5),
    ),
  );
  await Promise.all(
    chunks.map((chunk, index) =>
      writeFile(
        path.join(
          repoRoot,
          `ui/layout/src/sidebar-group-glyph-data-${index + 1}.ts`,
        ),
        dataModule(chunk, index + 1),
      ),
    ),
  );
  const tags = icons
    .map(
      ({ key }) => `  ${JSON.stringify(key)}: ${JSON.stringify(tagsFor(key))},`,
    )
    .join("\n");
  await writeFile(
    path.join(repoRoot, "ui/layout/src/sidebar-group-glyph-tags.ts"),
    `/** Generated curated concept tags. Name words are added by the matcher. */\nimport type { SidebarGroupGlyphName } from "./sidebar-group-glyphs";\n\nexport const SIDEBAR_GROUP_GLYPH_TAGS = {\n${tags}\n} satisfies Record<SidebarGroupGlyphName, readonly string[]>;\n`,
  );
  return icons;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const sourcePath = process.argv[2];
  if (!sourcePath) {
    throw new Error(
      "Usage: node scripts/generate-team-icons.mjs <team-icons.svg>",
    );
  }
  const icons = await generate(sourcePath);
  process.stdout.write(`Generated ${icons.length} team icons.\n`);
}
